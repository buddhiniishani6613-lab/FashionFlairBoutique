    private String getCategoryName(int categoryID) {

        switch (categoryID) {

            case 1:
                return "Casual Wear";

            case 2:
                return "Formal Wear";

            case 3:
                return "Sportswear";

            case 4:
                return "Footwear";

            case 5:
                return "Accessories";

            default:
                return "Unknown";
        }
    }
    
    private int getCategoryID(String categoryName) {

        switch (categoryName) {

            case "Casual Wear":
                return 1;

            case "Formal Wear":
                return 2;

            case "Sportswear":
                return 3;

            case "Footwear":
                return 4;

            case "Accessories":
                return 5;

            default:
                return 1;
        }
    }
    
