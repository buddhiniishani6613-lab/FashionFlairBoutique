    private void loadProducts() {

    dao.ProductDAO productDAO = new dao.ProductDAO();

    java.util.ArrayList<model.Product> products =
            productDAO.getAllProducts();

    javax.swing.table.DefaultTableModel tableModel =
            (javax.swing.table.DefaultTableModel) tblProducts.getModel();

    // Remove old rows before loading fresh data
    tableModel.setRowCount(0);

        for (model.Product product : products) {

            String categoryName =
                    getCategoryName(product.getCategoryID());

            tableModel.addRow(new Object[]{
                product.getProductID(),
                product.getProductName(),
                product.getBrand(),
                categoryName,
                product.getSize(),
                product.getColor(),
                product.getPrice(),
                product.getStockQuantity()
            });
        }
    }

