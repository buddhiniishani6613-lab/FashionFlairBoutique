    private void btnUpdateProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateProductActionPerformed
        // TODO add your handling code here:
            try {

           // Product ID is required for identifying the product
           if (txtProductID.getText().trim().isEmpty()) {

               javax.swing.JOptionPane.showMessageDialog(
                       this,
                       "Please select a product to update."
               );

               return;
           }

           // Read product details from the form
           int productID = Integer.parseInt(
                   txtProductID.getText().trim()
           );

           String productName = txtProductName.getText().trim();
           String brand = txtBrand.getText().trim();
           String categoryName = cmbCategory.getSelectedItem().toString();
           String size = txtSize.getText().trim();
           String color = txtColor.getText().trim();

           // Check required fields
           if (productName.isEmpty()
                   || brand.isEmpty()
                   || size.isEmpty()
                   || color.isEmpty()
                   || txtPrice.getText().trim().isEmpty()
                   || txtStock.getText().trim().isEmpty()) {

               javax.swing.JOptionPane.showMessageDialog(
                       this,
                       "Please fill all product details."
               );

               return;
           }

           // Convert category name to CategoryID
           int categoryID = getCategoryID(categoryName);

           // Convert price and stock
           double price = Double.parseDouble(
                   txtPrice.getText().trim()
           );

           int stock = Integer.parseInt(
                   txtStock.getText().trim()
           );

           // Validate values
           if (price < 0 || stock < 0) {

               javax.swing.JOptionPane.showMessageDialog(
                       this,
                       "Price and stock cannot be negative."
               );

               return;
           }

           // Create Product object
           model.Product product = new model.Product();

           product.setProductID(productID);
           product.setProductName(productName);
           product.setBrand(brand);
           product.setCategoryID(categoryID);
           product.setSize(size);
           product.setColor(color);
           product.setPrice(price);
           product.setStockQuantity(stock);

           // Update product through DAO
           dao.ProductDAO productDAO = new dao.ProductDAO();

           boolean success = productDAO.updateProduct(product);

           if (success) {

               javax.swing.JOptionPane.showMessageDialog(
                       this,
                       "Product updated successfully!"
               );

               // Refresh table
               loadProducts();

               // Clear fields
               clearFields();

           } else {

               javax.swing.JOptionPane.showMessageDialog(
                       this,
                       "Failed to update product."
               );
           }

       } catch (NumberFormatException e) {

           javax.swing.JOptionPane.showMessageDialog(
                   this,
                   "Please enter valid numbers for Product ID, Price and Stock."
           );

       } catch (Exception e) {

           javax.swing.JOptionPane.showMessageDialog(
                   this,
                   "Error updating product: " + e.getMessage()
           );
       }
    }//GEN-LAST:event_btnUpdateProductActionPerformed

